function GenericFactors({ alert, score }: {alert: Alert;score?: number;}) {
  const weights = alert.reasons.map((_, i) => Math.max(8, Math.round(38 / (i + 1))));
  const total = weights.reduce((a, w) => a + w, 0);
  return (
    <div className="bg-white rounded-lg shadow-lg border border-border overflow-hidden mb-8">
      <div className="p-6 border-b border-border flex flex-col md:flex-row md:items-center justify-between gap-4 bg-epi-bg/50">
        <div>
          <h2 className="text-[18px] font-bold text-epi-text">{alert.district} District — {alert.disease}</h2>
          <div className="text-[14px] text-epi-muted mt-1">
            Outbreak probability: <span className="font-bold text-epi-text">{alert.probability}%</span>
            {score !== undefined && <> | District risk score: <span className="font-bold text-epi-text">{score}/100</span></>}
          </div>
        </div>
        <SeverityBadge severity={alert.severity} />
      </div>
      <div className="p-6">
        <h3 className="text-[14px] font-bold text-epi-text mb-4">Contributing factors (share of score)</h3>
        <div className="space-y-3">
          {alert.reasons.map((r, i) =>
          <div key={r} className="text-[13px]">
              <div className="flex justify-between gap-3 mb-1">
                <span className="text-epi-text">{r}</span>
                <span className="font-bold text-epi-text">{Math.round(weights[i] / total * 100)}%</span>
              </div>
              <div className="h-2 bg-epi-bg rounded-full overflow-hidden">
                <div className="h-full bg-epi rounded-full" style={{ width: `${weights[i] / total * 100}%` }} />
              </div>
            </div>
          )}
        </div>
        <p className="text-[12px] text-epi-muted mt-4">
          Factor weights are illustrative — generated by the simulated prediction model from the alert's trigger reasons.
        </p>
        <Link to={`/warning/detail?id=${alert.id}`} className="inline-block mt-3 text-[13px] font-bold text-epi hover:underline">Open alert {alert.id} →</Link>
      </div>
    </div>);

}

